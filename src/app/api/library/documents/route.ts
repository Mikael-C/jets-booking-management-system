export async function GET(req: Request) {
  const { searchParams } = new URL(req.url);
  const type = searchParams.get("type");
  const status = searchParams.get("status");
  const search = (searchParams.get("search") || "").toLowerCase();

  let filtered = [...mockDocs];
  if (type && type !== "All 13" && type !== "All") {
    filtered = filtered.filter((d) => d.type.toLowerCase().includes(type.toLowerCase()));
  }
  if (status === "needs_review") {
    filtered = filtered.filter((d) => ["Lawyer review", "Awaiting policy", "Adviser review"].includes(d.status));
  }
  if (search) {
    filtered = filtered.filter(
      (d) => d.code.toLowerCase().includes(search) || d.title.toLowerCase().includes(search)
    );
  }

  return NextResponse.json({
    success: true,
    data: filtered,
    meta: {
      totalCount: 13,
      needsReviewCount: 6,
      staffAcknowledged: "3 of 4 staff acknowledged v1.0",
      curatorsAcknowledged: "18 of 21 Curators",
      nextReviewDoc: "Emergency checklist · Nov 2027",
    },
  });
}
