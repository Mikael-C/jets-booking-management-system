/**
 * Generate the complete fleet array of 200 aircraft
 */
function getFullFleet() {
  const fullFleet = [];

  RAW_FLEET_DEFINITIONS.forEach((catGroup) => {
    const { category, categoryLabel, aircraft: list } = catGroup;

    list.forEach((item, index) => {
      const imagesBundle = buildAircraftImages(category, index, item.name, {
        hasToilette: item.toilette,
        hasGalley: item.fullGalley,
      });

      const aircraftRecord = {
        name: item.name,
        manufacturer: item.manufacturer,
        category,
        categoryLabel: item.categoryLabel || categoryLabel,
        tagline: item.tagline || '',
        description: item.description || '',
        registration: '', // No tail numbers visible as requested
        model: item.name,
        yearManufactured: item.yearManufactured || 2020,
        yearRefurbished: item.yearRefurbished || 2024,
        passengers: item.passengers,
        passengersLabel: `${item.passengers} passengers`,
        range: item.range,
        rangeLabel: `${item.range.toLocaleString()} nm`,
        cruiseSpeedKtas: item.cruiseSpeedKtas || 450,
        cruiseSpeedLabel: `${item.cruiseSpeedKtas || 450} ktas`,
        maxAltitudeFt: item.maxAltitudeFt || 45000,
        cabinHeightM: item.cabinHeightM || '1.75 m',
        cabinWidthM: item.cabinWidthM || '1.80 m',
        cabinLengthM: item.cabinLengthM || '6.00 m',
        baggageVolumeCuFt: item.baggageVolumeCuFt || 50,
        engineType: item.name.includes('King Air') || category === 'turboprop' ? 'Turboprop' : category === 'piston' ? 'Piston' : 'Turbofan',
        engineCount: item.category === 'piston' && (item.name.includes('Cirrus') || item.name.includes('Mooney') || item.name.includes('Cessna 182') || item.name.includes('Cessna T206')) ? 1 : (item.name.includes('Falcon 900') || item.name.includes('Falcon 50') || item.name.includes('Falcon 7X') || item.name.includes('Falcon 8X')) ? 3 : (item.name.includes('747') || item.name.includes('JetStar')) ? 4 : 2,
        pricePerHour: item.pricePerHour,
        priceLabel: `$${item.pricePerHour.toLocaleString()} / hr`,
        // Amenities
        toilette: item.toilette ?? true,
        fullStandupCabin: item.fullStandupCabin ?? false,
        privateBedroom: item.privateBedroom ?? false,
        showerOnboard: item.showerOnboard ?? false,
        smokingCabin: false,
        wifiOnboard: true,
        microwave: item.fullGalley ?? false,
        fullGalley: item.fullGalley ?? false,
        satPhone: item.range > 3000,
        entertainmentSystem: true,
        sleepingBeds: item.sleepingBeds ?? 0,
        // Images
        imageExterior: imagesBundle.imageExterior,
        imageInterior: imagesBundle.imageInterior,
        images: imagesBundle.images,
        additionalImages: imagesBundle.additionalImages,
        isAvailable: true,
        homeBase: 'Geneva Cointrin / Le Bourget',
        homeBaseIcao: 'LSGG',
        notes: 'Curated Orbelo luxury fleet member with vetted Part 135 / EU-OPS certificate.',
      };

      fullFleet.push(aircraftRecord);
    });
  });

  return fullFleet;
}

